import assert from 'node:assert/strict';
const messages = [];
globalThis.location = {origin:'https://fly.test', search:'?fly-agent=1'};
globalThis.window = {parent:{postMessage:(message, origin) => messages.push({message, origin})}};
globalThis.document = {createElement: tag => ({tagName:tag})};
const {flyEmbedded, createFlyBootScreen, createFlyBattleLoader, createFlyGarage, createFlyGarageStage} = await import('./embedded.ts');
assert.equal(flyEmbedded,true);
const boot = createFlyBootScreen();
boot.begin('renderer');
assert.equal(messages.at(-1).origin, location.origin);
assert.equal(messages.at(-1).message.type,'progress');
let gesture = false;
await boot.ready(() => {gesture = true;});
assert.equal(gesture,false,'embedded boot has no splash entry gesture');
const loader = createFlyBattleLoader();
loader.showPending();
assert.equal(loader.covering,true);
loader.progress(.5,'Building battlefield');
assert.equal(messages.at(-1).message.fraction,.615);
await loader.hide();
assert.equal(loader.covering,false,'covered renderer gate releases without a second loading UI');
const garage = createFlyGarage();
garage.show();
assert.equal(garage.isOpen,false);
garage.setSelected('bmp2');garage.setSelectedMap('alpine');
assert.equal(garage.getSelected(),'bmp2');assert.equal(garage.getSelectedMap(),'alpine');
assert.deepEqual(garage.getNeighborIds(),[],'no unused vehicle preloads');
assert.equal(createFlyGarageStage().group.children.length,0,'no garage geometry');
console.log('fly embedded runtime: parent progress, no splash, covered reveal and empty garage PASS');
